def render_skill(lay: dict) -> str:
    t = (SKILL_SRC / "SKILL.md.tmpl").read_text()
    servers, p, laptop = lay["servers"], primary(lay), lay["laptop"].get("enabled")
    tools = [f"`{tool_name(s)}`" for s in servers]
    total = sum(s["lanes"] for s in servers)
    one = len(servers) == 1

    def server_line(s):
        note = f" {s['note'].rstrip('.')}." if s["note"] else ""
        cache = ""
        if s["lanes"] > 1:
            cache = f" **At most {s['lanes']} of your subagents running on it at once.**"
        else:
            cache = " **One subagent on it at a time.**"
        role = " Critic and writer run here." if s.get("primary") and not one else ""
        return f"- `{tool_name(s)}`: {s['contextWindow'] // 1024}K context.{note}{role}{cache}"

    if one:
        servers_section = ("There is one server, so every subagent goes through "
                           f"`{tool_name(p)}`, and so does your own conversation. It answers one request at a time "
                           "(the others wait their turn), which is why the number of live subagents is capped:\n\n"
                           + server_line(p))
    else:
        servers_section = ("The tools differ only in which server runs the subagent. Each server answers a fixed number of "
                           "requests at once; the rest wait. Keep to the lanes:\n\n"
                           + "\n".join(server_line(s) for s in servers))
    lanes_summary = ", ".join(f"{s['lanes']} on {s['name']}" for s in servers)
    rep = {
        "{{SERVER_NAMES}}": ", ".join(s["name"] for s in servers),
        "{{LAPTOP_DESC}}": " reads the pages plain fetching cannot get in a real browser," if laptop else "",
        "{{TOOLS_PLURAL}}": "" if one else "s",
        "{{TOOLS_LIST}}": " and ".join([", ".join(tools[:-1]), tools[-1]]) if len(tools) > 1 else tools[0],
        "{{TOOLS_PRONOUN}}": "it" if one else "them",
        "{{TOOLS_INTRO}}": (f"`{tool_name(p)}` starts one subagent and returns" if one
                            else "Each of them starts one subagent and returns"),
        "{{LAPTOP_PRESET_LINE}}": ("- `dr-laptop`: reads a batch of blocked pages in the laptop's real browser (shared "
                                   "laptop: one pass at a time).\n") if laptop else "",
        "{{SERVERS_SECTION}}": servers_section,
        "{{TOTAL_LANES}}": str(total),
        "{{PRIMARY_TOOL}}": tool_name(p),
        "{{LANES_SUMMARY}}": lanes_summary,
        "{{DSH_HOME}}": str(expand(lay["dsh_home"])),
        "{{LAPTOP_DIGEST}}": "the laptop findings; " if laptop else "",
        "{{LAPTOP_SEEN}}": ", a laptop pass" if laptop else "",
        "{{LAPTOP_NUMBERS}}": ", laptop passes" if laptop else "",
        "{{LAPTOP_CHECKS}}": (" Pages they could not read and videos they could not see go to one more laptop pass if "
                              "any of them decide a verdict.") if laptop else "",
    }
    if lay["search"] == "web_search":
        rep["{{SEARCH_SETUP}}"] = ("- Searching goes through dsh's `web_search` (its provider is configured here); when "
                                   "it errors, `SEARCH` through bash. Write `Search: web_search` into the brief.")
    else:
        rep["{{SEARCH_SETUP}}"] = ("- Searching goes through `SEARCH` (bash): it tries the engines whose keys are set "
                                   "(Exa first, then DuckDuckGo and other free engines) and says which engine answered. "
                                   "Write `Search: helper` into the brief. Do not use dsh's `web_search`: it has no "
                                   "provider credential here.")
    if laptop:
        rep["{{LAPTOP_STEP}}"] = textwrap.dedent("""\
            3. **Laptop.** Collect the `blocked` pages of the round, drop duplicates, sort by priority, keep at most 30, and
               split them into batches of at most 6. For each batch, one at a time (wait for its result before the next),
               on whichever server is free: `agent_preset` `dr-laptop`, description `Laptop pass <n>`, prompt: "Brief:
               <brief>. Pages, each with why it could not be fetched and what the research wants from it: <list>. Ask
               laptop_acquire for <min(30, 8 + 4 x pages)> minutes. Notes file: <OUT>/notes/laptop-<n>.md."
               A laptop held by another agent is not a reason to skip: the pass waits in line by itself. Skip only if a pass
               reports that the laptop tools are missing or the service is unreachable, and say so in the report. While a
               laptop pass runs, the other free slots may already run the next round's or the fact checks' tasks.""").rstrip()
    else:
        rep["{{LAPTOP_STEP}}"] = ("3. **Blocked pages.** No real-browser reader is set up here. Collect the round's `blocked` "
                                  "pages in the digest under \"could not be read\", look for the same facts elsewhere "
                                  "(archived copies, other pages) in the next round, and list them in the report's "
                                  "methodology.")
    for k, v in rep.items():
        t = t.replace(k, v)
    left = re.findall(r"\{\{[A-Z_]+\}\}", t)
    if left:
        die(f"unrendered placeholders in SKILL.md: {sorted(set(left))}")
    return t


