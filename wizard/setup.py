#!/usr/bin/env python3
"""dsh-deep-research setup wizard: renders the deep-research skill and a DeepSeek Harness profile for YOUR
inference layout, checks the servers, and installs it.

    python3 wizard/setup.py init   [-o layout.json]        ask about your servers, probe them, write a layout file
    python3 wizard/setup.py check  layout.json              probe every server in the layout (models, chat, tool call, pictures)
    python3 wizard/setup.py render layout.json -o DIR       write everything into DIR without touching dsh (review it)
    python3 wizard/setup.py install layout.json [--systemd] [--force]
                                                            install into $DSH_HOME and the dsh install prefix

Stdlib only (Python 3.10+). The layout format is documented in docs/LAYOUT.md; examples in wizard/layouts/.
What it installs (docs/AGENT-SETUP.md has the long form):
  <dsh_home>/profiles/<profile>/cordis.patch.yml   routes + 5 agent presets (a profile of its own: yours stay untouched)
  <dsh_home>/profiles/<profile>/{package.json,cordis.yml,pnpm-workspace.yaml}   seeded only when absent
  <dsh_home>/skills/deep-research/                  SKILL.md rendered for the layout + the fetch/frames/search helpers
  <dsh_install>/plugins/bounded-compaction.mjs      the compaction engine every preset mounts
  ~/.config/systemd/user/dsh-<profile>.service      with --systemd (not enabled: the command is printed)
"""
