SEED_PACKAGE = {"name": "dsh-profile-{p}", "private": True, "dependencies": {},
                "dsh": {"profile": {"bundles": ["@deepseek-ai/dsh-base", "@deepseek-ai/dsh-web-app"]}}}
SEED_CORDIS = ("# dsh profile root: an empty entry list. The tree is composed as patches: each bundle in package.json's\n"
               "# dsh.profile.bundles, then cordis.patch.yml. Edit cordis.patch.yml, not this file.\n[]\n")
SEED_PNPM = "packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n"


def unit_text(lay: dict) -> str:
    install = expand(lay["dsh_install"])
    path = os.pathsep.join(dict.fromkeys([str(pathlib.Path(shutil.which("uv") or "/usr/bin/uv").parent),
                                          str(pathlib.Path(shutil.which("node") or "/usr/bin/node").parent),
                                          "/usr/local/bin", "/usr/bin", "/bin"]))
    return textwrap.dedent(f"""\
        {MARKER}
        [Unit]
        Description=DeepSeek Harness web UI, profile {lay['profile']} (dsh-deep-research)
        After=network-online.target
        Wants=network-online.target

        [Service]
        Type=simple
        Environment=DSH_HOME={expand(lay['dsh_home'])}
        # the research helpers run through uv: it must be on the service's PATH
        Environment=PATH={path}
        # search keys (EXA_API_KEY=..., optional; docs/SEARCH.md) and the laptop's client token (CU_TOKEN=..., optional)
        EnvironmentFile=-%h/.config/dsh/search.env
        EnvironmentFile=-%h/.config/computer-use/client.env
        ExecStart={install}/node_modules/.bin/dsh --profile {lay['profile']} --no-open --port {lay['port']}
        Restart=on-failure
        RestartSec=5

        [Install]
        WantedBy=default.target
        """)


def render_all(lay: dict, out: pathlib.Path) -> dict[str, pathlib.Path]:
    out.mkdir(parents=True, exist_ok=True)
    files = {}
    (out / "cordis.patch.yml").write_text(render_profile(lay))
    files["profile"] = out / "cordis.patch.yml"
    skill = out / "skills" / "deep-research"
    if skill.exists():
        shutil.rmtree(skill)
    shutil.copytree(SKILL_SRC, skill, ignore=shutil.ignore_patterns("SKILL.md.tmpl", "__pycache__", "*.pyc"))
    (skill / "SKILL.md").write_text(render_skill(lay))
    files["skill"] = skill
    (out / f"dsh-{lay['profile']}.service").write_text(unit_text(lay))
    files["unit"] = out / f"dsh-{lay['profile']}.service"
    return files


def backup(path: pathlib.Path, home: pathlib.Path) -> None:
    """Moves a file or folder we are about to replace OUT of dsh's scan roots (a copy left in skills/ would be
    discovered as a second deep-research skill) into <dsh_home>/dsh-deep-research-backups/<timestamp>/."""
    if path.exists():
        dst = home / "dsh-deep-research-backups" / f"{datetime.datetime.now():%Y%m%d-%H%M%S}" / path.relative_to(home)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(path), dst)
        print(f"  backed up {path} -> {dst}")


def cmd_install(lay: dict, systemd: bool, force: bool) -> int:
    home, install = expand(lay["dsh_home"]), expand(lay["dsh_install"])
    if not (install / "node_modules" / "@deepseek-ai" / "dsh-compaction-basic").exists():
        die(f"no dsh install under {install} (the compaction plugin resolves its imports there). Install it first:\n"
            f"  npm install --prefix {install} @deepseek-ai/dsh@{TESTED_DSH}\nor set dsh_install in the layout.")
    prof = home / "profiles" / lay["profile"]
    patch = prof / "cordis.patch.yml"
    if patch.exists() and MARKER not in patch.read_text().split("\n", 1)[0] and not force:
        die(f"{patch} exists and was not written by this wizard. Pick another profile name in the layout, or pass "
            "--force (the old file is kept as a .bak).")
    stage = REPO / ".render" / lay["profile"]
    files = render_all(lay, stage)
    print(f"rendered into {stage}")
    prof.mkdir(parents=True, exist_ok=True)
    if patch.exists():
        backup(patch, home)
    shutil.copy(files["profile"], patch)
    os.chmod(patch, 0o600)
    print(f"  wrote {patch}")
    seeds = {"package.json": json.dumps(SEED_PACKAGE).replace("{p}", lay["profile"]) + "\n",
             "cordis.yml": SEED_CORDIS, "pnpm-workspace.yaml": SEED_PNPM}
    for name, text in seeds.items():
        if not (prof / name).exists():  # dsh owns them after the first boot
            (prof / name).write_text(text)
            print(f"  seeded {prof / name}")
    dst = home / "skills" / "deep-research"
    if dst.exists():
        backup(dst, home)
    shutil.copytree(files["skill"], dst)
    print(f"  wrote {dst}/")
    (install / "plugins").mkdir(parents=True, exist_ok=True)
    shutil.copy(PLUGIN, install / "plugins" / PLUGIN.name)
    print(f"  wrote {install / 'plugins' / PLUGIN.name}")
    run = f"DSH_HOME={home} {install}/node_modules/.bin/dsh --profile {lay['profile']} --port {lay['port']}"
    if systemd:
        unit = pathlib.Path.home() / ".config" / "systemd" / "user" / f"dsh-{lay['profile']}.service"
        if unit.exists() and MARKER not in unit.read_text() and not force:
            die(f"{unit} exists and was not written by this wizard (--force replaces it)")
        unit.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(files["unit"], unit)
        print(f"  wrote {unit}")
        run = (f"systemctl --user daemon-reload && systemctl --user enable --now dsh-{lay['profile']}.service\n"
               f"  journalctl --user -u dsh-{lay['profile']} -n 50   # the first-visit URL with its token")
    lap = lay["laptop"]
    print(textwrap.dedent(f"""
        Done. Next:
          1. Start the web UI:  {run}
          2. Open it, New Session -> pick the "Deep research" preset (headless dsh composes no presets: use the web UI).
          3. Type: /deep-research <a narrow question>. 1 round, 3 sub-questions{', no laptop pass' if lap.get('enabled') else ''}
             for the first run, and watch the subagents appear on each server.
        Optional: EXA_API_KEY=... in ~/.config/dsh/search.env (mode 600) for the best search results (docs/SEARCH.md).""")
          + (f"\n  Laptop: {lap['tokenEnv']}=... in ~/.config/computer-use/client.env (mode 600)." if lap.get("enabled")
             and lap["transport"] == "http" else ""))
    return 0


# ── init (interactive) ───────────────────────────────────────────────────────────────────────────────────

def ask(prompt: str, default: str = "") -> str:
    v = input(f"{prompt}{f' [{default}]' if default else ''}: ").strip()
    return v or default


def yes(prompt: str, default: bool) -> bool:
    v = ask(prompt + (" (Y/n)" if default else " (y/N)")).lower()
    return default if not v else v.startswith("y")


def cmd_init(out: str) -> int:
    print(textwrap.dedent("""\
        dsh-deep-research setup. You need: DeepSeek Harness installed, and one or more OpenAI-compatible model servers
        (llama.cpp's llama-server or a fork, vLLM, ...) serving a model that calls tools well and holds >= 64K context.
        Each server becomes a lane group: a 'research_<name>' tool the orchestrator delegates through.
        """))
    lay = {"profile": ask("dsh profile to create (keep it separate from your daily one)", "research"),
           "dsh_home": ask("DSH_HOME", os.environ.get("DSH_HOME", "~/.dsh")),
           "dsh_install": ask("dsh install prefix (where node_modules/@deepseek-ai/dsh lives)", "~/.local/share/dsh"),
           "port": int(ask("web UI port", "3080")), "servers": []}
    n = int(ask("how many model servers", "1"))
    for i in range(n):
        print(f"\nserver {i + 1} of {n}")
        name = ask("  short name (a-z, 0-9, -)", ["main", "second", "third", "fourth"][i] if i < 4 else f"s{i + 1}")
        base = ask("  base URL (ends in /v1)", "http://127.0.0.1:8080/v1")
        s = {"name": name, "baseURL": base}
        try:
            ids = [m["id"] for m in http(base.rstrip("/") + "/models", timeout=10).get("data", [])]
            print(f"  serves: {', '.join(ids)}")
        except Exception as e:
            ids = []
            print(f"  (could not list models: {e})")
        s["model"] = ask("  model id", ids[0] if ids else "")
        ctx = ""
        try:
            props = http(base.rstrip("/").removesuffix("/v1") + "/props", timeout=10)
            ctx = str((props.get("default_generation_settings") or {}).get("n_ctx") or props.get("n_ctx") or "")
        except Exception:
            pass
        s["contextWindow"] = int(ask("  context window in tokens (what the server holds)", ctx or "131072"))
        print("  lanes = how many subagents may use this server at once. 1 unless the server keeps idle conversations\n"
              "  (llama.cpp --cache-ram, a conversation cache) or has several slots with KV for each (docs/LAYOUT.md).")
        s["lanes"] = int(ask("  lanes", "2" if s["contextWindow"] >= 131072 else "1"))
        s["vision"] = yes("  does it read pictures (an mmproj / vision model)?", False)
        qwen = yes("  is it a Qwen 3.x reasoning model (thinking switched by chat_template_kwargs)?", True)
        s["thinking"] = "qwen-chat-template" if qwen else "none"
        key = ask("  env var holding its API key (empty: none)", "")
        if key:
            s["apiKeyEnv"] = key
        s["note"] = ask("  one line for the orchestrator about it (speed, quirks)", "")
        lay["servers"].append(s)
    if n > 1:
        names = [s["name"] for s in lay["servers"]]
        p = ask(f"primary server (orchestrator, critic, writer; longest context) {names}",
                max(lay["servers"], key=lambda s: s["contextWindow"])["name"])
        for s in lay["servers"]:
            if s["name"] == p:
                s["primary"] = True
    lay["search"] = "helper"
    if yes("\nset up the laptop MCP (a real Chrome on a Windows PC, for bot-walled pages; laptop-mcp/README.md)?", False):
        t = ask("  transport: http (a shared service with a token) or stdio (this machine drives the laptop over ssh)", "stdio")
        if t == "http":
            lay["laptop"] = {"enabled": True, "transport": "http", "url": ask("  service URL", "https://laptop.example.lan/mcp"),
                             "tokenEnv": "CU_TOKEN"}
        else:
            lay["laptop"] = {"enabled": True, "transport": "stdio", "repo": str(REPO / "laptop-mcp"),
                             "env": {"CU_HOST": ask("  ssh host of the laptop", "laptop"),
                                     "CU_AGENT_USER": ask("  Windows account the agents drive", "agent")}}
    else:
        lay["laptop"] = {"enabled": False}
    pathlib.Path(out).write_text(json.dumps(lay, indent=2) + "\n")
    print(f"\nwrote {out}. Next: python3 wizard/setup.py check {out}  then  install {out}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init")
    i.add_argument("-o", "--out", default="layout.json")
    c = sub.add_parser("check")
    c.add_argument("layout")
    r = sub.add_parser("render")
    r.add_argument("layout")
    r.add_argument("-o", "--out", required=True)
    n = sub.add_parser("install")
    n.add_argument("layout")
    n.add_argument("--systemd", action="store_true", help="also write a systemd user unit (not enabled)")
    n.add_argument("--force", action="store_true", help="replace a profile/unit this wizard did not write (backed up)")
    a = ap.parse_args()
    if a.cmd == "init":
        return cmd_init(a.out)
    lay = load_layout(a.layout)
    if a.cmd == "check":
        return cmd_check(lay)
    if a.cmd == "render":
        files = render_all(lay, pathlib.Path(a.out))
        for k, v in files.items():
            print(f"{k}: {v}")
        return 0
    return cmd_install(lay, a.systemd, a.force)


if __name__ == "__main__":
    sys.exit(main())
