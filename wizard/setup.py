def http(url: str, body=None, key: str | None = None, timeout: float = 60):
    headers = {"Content-Type": "application/json", "Authorization": f"Bearer {key or 'none'}"}
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, headers=headers, method="POST" if data else "GET")
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.load(r)


def tiny_png() -> bytes:
    import struct
    import zlib

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + b"\xff\x00\x00" * 8 for _ in range(8))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 8, 8, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def probe(s: dict) -> list[tuple[str, bool, str]]:
    """(check, ok, detail) rows for one server."""
    base = s["baseURL"].rstrip("/")
    key = os.environ.get(s["apiKeyEnv"]) if s.get("apiKeyEnv") else None
    rows = []
    try:
        ids = [m.get("id") for m in http(f"{base}/models", key=key, timeout=15).get("data", [])]
        rows.append(("models", True, ", ".join(map(str, ids)) or "(empty list)"))
    except Exception as e:
        rows.append(("models", False, f"{type(e).__name__}: {e}"))
        return rows
    try:  # llama.cpp and forks report the served context at /props
        props = http(base.removesuffix("/v1") + "/props", key=key, timeout=10)
        n_ctx = (props.get("default_generation_settings") or {}).get("n_ctx") or props.get("n_ctx")
        if n_ctx:
            ok = n_ctx >= s["contextWindow"]
            rows.append(("context", ok, f"server n_ctx {n_ctx}, layout contextWindow {s['contextWindow']}"
                         + ("" if ok else ": the layout claims more than the server holds")))
    except Exception:
        pass
    msg = {"model": s["model"], "max_tokens": 32, "temperature": 0,
           "messages": [{"role": "user", "content": "Reply with the single word: ready"}]}
    if s["thinking"] == "qwen-chat-template":
        msg["chat_template_kwargs"] = {"enable_thinking": False}
    try:
        r = http(f"{base}/chat/completions", msg, key=key, timeout=600)
        rows.append(("chat", True, repr((r["choices"][0]["message"].get("content") or "")[:60])))
    except Exception as e:
        rows.append(("chat", False, f"{type(e).__name__}: {e}"))
        return rows
    tool = {"model": s["model"], "max_tokens": 512, "temperature": 0,
            "messages": [{"role": "user", "content": "Use the get_time tool for the city Rome."}],
            "tools": [{"type": "function", "function": {"name": "get_time", "description": "Current time in a city",
                       "parameters": {"type": "object", "properties": {"city": {"type": "string"}},
                                      "required": ["city"]}}}]}
    if s["thinking"] == "qwen-chat-template":
        tool["chat_template_kwargs"] = {"enable_thinking": False}
    try:
        r = http(f"{base}/chat/completions", tool, key=key, timeout=600)
        calls = r["choices"][0]["message"].get("tool_calls") or []
        ok = bool(calls) and calls[0]["function"]["name"] == "get_time"
        rows.append(("tool call", ok, calls[0]["function"]["arguments"] if ok else
                     "no structured tool_calls: check the server's chat template / --jinja"))
    except Exception as e:
        rows.append(("tool call", False, f"{type(e).__name__}: {e}"))
    if s["vision"]:
        for label, mime, data in (("picture png", "image/png", tiny_png()),
                                  ("picture webp+alpha", "image/webp", base64.b64decode(WEBP_ALPHA))):
            img = {"model": s["model"], "max_tokens": 16, "temperature": 0, "messages": [{"role": "user", "content": [
                {"type": "text", "text": "What colour is this picture? One word."},
                {"type": "image_url", "image_url": {"url": f"data:{mime};base64,{base64.b64encode(data).decode()}"}}]}]}
            if s["thinking"] == "qwen-chat-template":
                img["chat_template_kwargs"] = {"enable_thinking": False}
            try:
                r = http(f"{base}/chat/completions", img, key=key, timeout=600)
                rows.append((label, True, repr((r["choices"][0]["message"].get("content") or "")[:40])))
            except urllib.error.HTTPError as e:
                rows.append((label, False, f"HTTP {e.code}: {e.read()[:200].decode(errors='replace')}"))
            except Exception as e:
                rows.append((label, False, f"{type(e).__name__}: {e}"))
    return rows


def cmd_check(lay: dict) -> int:
    bad = 0
    for s in lay["servers"]:
        print(f"\n{s['name']}  {s['baseURL']}  ({s['model']}, {s['lanes']} lane(s){', primary' if s.get('primary') else ''})")
        for check, ok, detail in probe(s):
            bad += not ok
            print(f"  {'PASS' if ok else 'FAIL'}  {check:<20} {detail}")
    tools = [("uv", "runs the fetch/frames/search helpers"), ("zstdcat", "reads a failed subagent's error"),
             ("deno", "yt-dlp's JavaScript runtime for YouTube frames (optional)"),
             ("magick", "converts pictures a server refuses (optional)")]
    print("\nthis machine")
    for t, why in tools:
        found = shutil.which(t)
        if not found and t in ("uv", "zstdcat"):
            bad += 1
        print(f"  {'PASS' if found else ('FAIL' if t in ('uv', 'zstdcat') else 'WARN')}  {t:<20} {found or 'missing: ' + why}")
    dsh = expand(lay["dsh_install"]) / "node_modules" / ".bin" / "dsh"
    hint = f"not at {dsh}: npm install --prefix {expand(lay['dsh_install'])} @deepseek-ai/dsh@{TESTED_DSH}"
    print(f"  {'PASS' if dsh.exists() else 'FAIL'}  {'dsh':<20} {dsh if dsh.exists() else hint}")
    bad += not dsh.exists()
    print(f"\n{'all checks passed' if not bad else f'{bad} check(s) failed'}")
    return 1 if bad else 0


