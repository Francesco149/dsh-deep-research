THINKING = ("qwen-chat-template", "none")


def die(msg: str) -> None:
    sys.exit(f"setup: {msg}")


def expand(p: str) -> pathlib.Path:
    return pathlib.Path(os.path.expandvars(os.path.expanduser(p)))


def load_layout(path: str) -> dict:
    try:
        lay = json.loads(pathlib.Path(path).read_text())
    except (OSError, ValueError) as e:
        die(f"cannot read layout {path}: {e}")
    lay.setdefault("profile", "research")
    lay.setdefault("dsh_home", os.environ.get("DSH_HOME", "~/.dsh"))
    lay.setdefault("dsh_install", "~/.local/share/dsh")
    lay.setdefault("port", 3080)
    lay.setdefault("search", "helper")
    lay.setdefault("worker_compaction_ratio", 0.2)
    lay.setdefault("laptop", {"enabled": False})
    servers = lay.get("servers") or die("the layout has no servers")
    names = set()
    for s in servers:
        for k in ("name", "baseURL", "model", "contextWindow"):
            if k not in s:
                die(f"server {s.get('name', '?')}: missing {k!r}")
        if not re.fullmatch(r"[a-z][a-z0-9-]{0,30}", s["name"]):
            die(f"server name {s['name']!r}: lowercase letters, digits and '-', starting with a letter")
        if s["name"] in names:
            die(f"server name {s['name']!r} twice")
        names.add(s["name"])
        s.setdefault("displayName", f"{s['model']} ({s['name']})")
        s.setdefault("maxTokens", 16384)
        s.setdefault("lanes", 1)
        s.setdefault("vision", False)
        s.setdefault("thinking", "qwen-chat-template")
        s.setdefault("reasoningEffort", "medium")
        s.setdefault("reasoningEfforts", ["low", "medium", "xhigh"])
        s.setdefault("timeoutMs", 1800000)
        s.setdefault("streamIdleTimeoutMs", 900000)
        s.setdefault("note", "")
        if s["thinking"] not in THINKING:
            die(f"server {s['name']}: thinking must be one of {THINKING}")
        if not isinstance(s["lanes"], int) or s["lanes"] < 1:
            die(f"server {s['name']}: lanes must be a whole number >= 1")
    prim = [s for s in servers if s.get("primary")]
    if len(prim) > 1:
        die("more than one server has primary: true")
    if not prim:  # the longest context runs the orchestrator, the critic and the writer
        max(servers, key=lambda s: s["contextWindow"])["primary"] = True
    total = sum(s["lanes"] for s in servers)
    if total > MAX_LIVE_SUBAGENTS:
        die(f"{total} lanes in all: dsh refuses more than {MAX_LIVE_SUBAGENTS} live subagents per session "
            "(maxActiveSubagents). Lower some server's lanes.")
    lap = lay["laptop"]
    if lap.get("enabled"):
        lap.setdefault("transport", "http")
        if lap["transport"] == "http":
            lap.get("url") or die("laptop.url is needed for transport http")
            lap.setdefault("tokenEnv", "CU_TOKEN")
        elif lap["transport"] == "stdio":
            lap.setdefault("repo", str(REPO / "laptop-mcp"))
            lap.setdefault("env", {})
        else:
            die("laptop.transport must be http or stdio")
    return lay


def primary(lay: dict) -> dict:
    return next(s for s in lay["servers"] if s.get("primary"))


def tool_name(s: dict) -> str:
    return "research_" + s["name"].replace("-", "_")


def nothink_route(s: dict) -> str:
    return s["name"] + "-nothink" if s["thinking"] == "qwen-chat-template" else s["name"]


# ── YAML emission (hand-written: the patch must stay readable, and stdlib has no YAML) ─────────────────────

def q(v) -> str:
    """A YAML scalar. JSON's string syntax is valid YAML."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if v is None:
        return ""
    return json.dumps(str(v), ensure_ascii=False)


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "|-\n" + "\n".join((pad + line) if line.strip() else "" for line in text.rstrip("\n").split("\n"))


def route_yaml(s: dict, nothink: bool) -> str:
    name = nothink_route(s) if nothink else s["name"]
    label = s["displayName"] + (", no thinking" if nothink else "")
    out = [f"      {name}:",
           f"        displayName: {q(label)}",
           "        api: openai-completions",
           f"        baseURL: {q(s['baseURL'])}"]
    if s.get("apiKeyEnv"):
        out.append(f"        apiKeyEnv: {q(s['apiKeyEnv'])}")
    else:
        # llama.cpp-style servers need no key, but the OpenAI client needs *a* credential
        out += ["        headers:", "          Authorization: Bearer none"]
    out += [f"        reasoning: {'off' if nothink else s['reasoningEffort'] if s['thinking'] != 'none' else 'off'}",
            f"        timeoutMs: {s['timeoutMs']}",
            f"        streamIdleTimeoutMs: {s['streamIdleTimeoutMs']}",
            "        compat:",
            "          supportsDeveloperRole: false",
            "          maxTokensField: max_tokens"]
    if s["thinking"] == "qwen-chat-template":
        out += ["          thinkingFormat: chat-template",
                "          chatTemplateKwargs:",
                "            enable_thinking:",
                "              $var: thinking.enabled",
                "            preserve_thinking: true",
                "            reasoning_effort:",
                "              $var: thinking.effort"]
    out += ["        models:",
            f"          - id: {q(s['model'])}",
            f"            name: {q(label[:-1] + ', vision)' if s['vision'] and label.endswith(')') else label + (' (vision)' if s['vision'] else ''))}",
            f"            input: [{'text, image' if s['vision'] else 'text'}]",
            f"            contextWindow: {s['contextWindow']}",
            f"            maxTokens: {s['maxTokens']}"]
    if s["thinking"] == "qwen-chat-template":
        out.append("            reasoningEfforts:")
        out.append("              off:")
        out += [f"              {e}: {e}" for e in s["reasoningEfforts"]]
    return "\n".join(out)


def compaction_yaml(lay: dict, ratio: float, indent: int, command: bool = False) -> str:
    p = primary(lay)
    install = expand(lay["dsh_install"])
    rows = [
        "- id: compaction",
        "  name: cordis:group",
        "  group: true",
        "  isolate:",
        "    compaction: true",
        "    toolResultPruner: true",
        "  config:",
        "    - id: compaction-basic",
        f"      name: {q(str(install / 'plugins' / 'bounded-compaction.mjs'))}",
        "      config:",
        f"        thresholdRatio: {ratio}",
        "        headroomTokens: 16384",
        "        retainTokens: 20000",
        f"        summarizationProvider: {q(nothink_route(p))}",
        f"        summarizationModel: {q(p['model'])}",
        "        maxTokens: 32768",
    ]
    if command:
        rows += ["    - id: command-compact", "      name: '@deepseek-ai/dsh-command-compact'"]
    rows += ["    - id: tool-result-pruner",
             "      name: '@deepseek-ai/dsh-compaction-tool-result-pruner'",
             "      config:",
             "        thresholdChars: 8192",
             "        headChars: 4096",
             "        tailChars: 1024"]
    pad = " " * indent
    return "\n".join(pad + r for r in rows)


def persona(name: str, lay: dict) -> str:
    text = (PERSONAS / f"{name}.md").read_text()
    servers = lay["servers"]
    return text.replace("{{SERVER_COUNT_WORDS}}", "one local model server" if len(servers) == 1
                        else f"{len(servers)} local model servers")


def preset_yaml(pid: str, name: str, desc: str, order: int, plugins: list[str]) -> str:
    return "\n".join([
        f"    - id: preset-{pid}",
        "      name: '@deepseek-ai/dsh-agent-preset'",
        "      config:",
        f"        id: {pid}",
        f"        name: {q(name)}",
        f"        description: {q(desc)}",
        f"        order: {order}",
        "        plugins:",
        *plugins,
    ])


def plug(pid: str, pkg: str, config: list[str] | None = None) -> str:
    out = [f"          - id: {pid}", f"            name: '{pkg}'"]
    if config:
        out += ["            config:"] + [f"              {c}" for c in config]
    return "\n".join(out)


def persona_plug(text: str) -> str:
    return "\n".join(["          - id: persona",
                      "            name: '@deepseek-ai/dsh-persona'",
                      "            config:",
                      "              prefix: " + block(text, 16)])


def laptop_mcp_yaml(lay: dict) -> str:
    lap = lay["laptop"]
    out = ["          - id: mcp-laptop",
           "            name: '@deepseek-ai/dsh-mcp-client'",
           "            config:",
           "              serverName: laptop"]
    if lap["transport"] == "http":
        out += ["              transport: streamable-http",
                f"              url: {q(lap['url'])}",
                "              headers:",
                # the token comes from the service environment, never from this file
                f"                Authorization: !!js \"'Bearer ' + process.env.{lap['tokenEnv']}\""]
    else:
        repo = expand(lap["repo"])
        # stdio children start from a scrubbed environment: name everything the server needs
        env = {"PATH": os.pathsep.join(dict.fromkeys(
                   [str(pathlib.Path(shutil.which("uv") or "/usr/bin/uv").parent),
                    str(pathlib.Path(shutil.which("ssh") or "/usr/bin/ssh").parent), "/usr/bin", "/bin"])),
               "HOME": str(pathlib.Path.home()), "CU_OWNER": "dsh deep research", **lap["env"]}
        out += ["              transport: stdio",
                f"              command: {q(str(repo / 'bin' / 'cu-mcp'))}",
                "              env:"] + [f"                {k}: {q(v)}" for k, v in env.items()]
    out += ["              # laptop_acquire waits in line up to 10 minutes per call",
            "              toolCallTimeoutMs: 900000",
            "              reconnect:",
            "                enabled: true",
            "                initialDelayMs: 1000",
            "                maxDelayMs: 30000",
            "                maxAttempts: 10"]
    return "\n".join(out)


def render_profile(lay: dict) -> str:
    p = primary(lay)
    laptop = lay["laptop"].get("enabled")
    servers = lay["servers"]
    web_cfg = ["fetch: false", "searchTimeoutMs: 60000"]
    head = textwrap.dedent(f"""\
        {MARKER} on {datetime.date.today().isoformat()} from layout profile {lay['profile']!r}.
        # Tested against dsh {TESTED_DSH}. Re-run the wizard to change it; hand edits are fine but are lost on re-install.
        #
        # Layout: {', '.join(f"{s['name']} ({s['lanes']} lane{'s' if s['lanes'] > 1 else ''})" for s in servers)};
        # orchestrator, critic, writer and compaction summaries on {p['name']}.
        # docs/HOW-IT-WORKS.md explains every row; docs/TROUBLESHOOTING.md the footguns (notably: edit this file, not the
        # Web settings editor, which can delete a preset row it is asked to reset).
        """)
    routes = []
    for s in servers:
        routes.append(route_yaml(s, False))
        if s["thinking"] == "qwen-chat-template":
            routes.append(route_yaml(s, True))
    out = [head,
           "# ── model routes: one per server, plus a no-thinking twin for compaction summaries ──",
           "- id: llm-pi-ai", "  config:", "    providers:", "\n\n".join(routes), "",
           "- id: agent-default-model", "  config:", f"    provider: {q(p['name'])}", f"    model: {q(p['model'])}",
           f"    reasoningEffort: {q(p['reasoningEffort'])}", "",
           "# ── deep research: the orchestrator and the four subagent types ──",
           "- insert:"]

    # orchestrator
    names = ", ".join(s["name"] for s in servers)
    orch = persona("deep-research", lay)
    tools = [plug("tool-subagent-control", "@deepseek-ai/dsh-tool-subagent-control"),
             plug("tool-subagent-list-agents", "@deepseek-ai/dsh-tool-subagent-control/list-agents")]
    for s in servers:
        allowed = ["dr-worker", "dr-critic", "dr-writer"] if s.get("primary") else ["dr-worker"]
        if laptop:
            allowed.append("dr-laptop")
        tools.append(plug(f"tool-research-{s['name']}", "@deepseek-ai/dsh-tool-subagent", [
            "provider: spawn", f"toolName: {tool_name(s)}", "agentOptions:", f"  provider: {q(s['name'])}",
            f"  model: {q(s['model'])}", f"  reasoningEffort: {q(s['reasoningEffort'])}", "agentPreset: dr-worker",
            f"allowedAgentPresets: [{', '.join(allowed)}]", "maxDepth: 1"]))
    delegation = "\n".join(["          - id: delegation", "            name: cordis:group", "            group: true",
                            "            config:"] + ["  " + line for t in tools for line in t.split("\n")])
    common = [plug("time-context", "@deepseek-ai/dsh-time-context"), plug("tool-bash", "@deepseek-ai/dsh-tool-bash")]
    out.append(preset_yaml("deep-research", "Deep research", f"Orchestrates /deep-research on the local servers ({names}).", 5, [
        persona_plug(orch), *common,
        plug("tool-fs", "@deepseek-ai/dsh-tool-fs"),
        plug("tool-fs-search", "@deepseek-ai/dsh-tool-fs-search", ["sampleOverCapGlobResults: false"]),
        plug("tool-jobs", "@deepseek-ai/dsh-tool-jobs"),
        plug("skill-filesystem", "@deepseek-ai/dsh-skill-filesystem"),
        plug("tool-skill", "@deepseek-ai/dsh-tool-skill"),
        plug("tool-ask-user", "@deepseek-ai/dsh-tool-ask-user"),
        plug("tool-todo", "@deepseek-ai/dsh-tool-todo", ["allowParallelInProgress: true"]),
        plug("tool-web", "@deepseek-ai/dsh-tool-web", web_cfg),
        compaction_yaml(lay, 0.9, 10, command=True),
        delegation]))
    out.append("")
    out.append(preset_yaml("dr-worker", "Deep research: worker (subagent)",
                           "One sub-question or one fact check on the web; notes with verbatim quotes.", 90, [
        persona_plug(persona("dr-worker", lay)), *common,
        plug("tool-fs", "@deepseek-ai/dsh-tool-fs"), plug("tool-jobs", "@deepseek-ai/dsh-tool-jobs"),
        plug("tool-web", "@deepseek-ai/dsh-tool-web", web_cfg),
        "          # Workers compact early so the contexts sharing one server fit its conversation cache\n"
        "          # (docs/HOW-IT-WORKS.md \"Worker compaction\"); findings live in the notes file.",
        compaction_yaml(lay, lay["worker_compaction_ratio"], 10)]))
    out.append("")
    out.append(preset_yaml("dr-critic", "Deep research: critic (subagent)",
                           "Gap review after a round; review of the finished report against its evidence.", 91, [
        persona_plug(persona("dr-critic", lay)), *common,
        plug("tool-fs", "@deepseek-ai/dsh-tool-fs", ["write: false", "edit: false"]),
        plug("tool-web", "@deepseek-ai/dsh-tool-web", web_cfg),
        compaction_yaml(lay, 0.9, 10)]))
    out.append("")
    out.append(preset_yaml("dr-writer", "Deep research: writer (subagent)",
                           "Writes report.md from the run's material and revises it on the reviewer's issues.", 92, [
        persona_plug(persona("dr-writer", lay)), *common, plug("tool-fs", "@deepseek-ai/dsh-tool-fs"),
        compaction_yaml(lay, 0.9, 10)]))
    if laptop:
        out.append("")
        out.append(preset_yaml("dr-laptop", "Deep research: laptop reader (subagent)",
                               "Reads a batch of blocked pages in the laptop's real Chrome, one laptop session per batch.", 93, [
            persona_plug(persona("dr-laptop", lay)), plug("time-context", "@deepseek-ai/dsh-time-context"),
            plug("tool-fs", "@deepseek-ai/dsh-tool-fs", ["edit: false"]),
            "          # The laptop MCP lives in this preset only: nobody else pays for its ~30 tool schemas.",
            laptop_mcp_yaml(lay),
            compaction_yaml(lay, 0.9, 10)]))
    return "\n".join(out) + "\n"


